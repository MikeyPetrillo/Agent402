const DAY_MS = 86400000;
const pad2 = (n) => String(n).padStart(2, "0");
const isoOf = (y, m, d) => `${y}-${pad2(m)}-${pad2(d)}`;
const wdOf = (iso) => new Date(iso + "T00:00:00Z").getUTCDay();
const shiftIso = (iso, n) => new Date(Date.parse(iso + "T00:00:00Z") + n * DAY_MS).toISOString().slice(0, 10);
const isWeekday = (iso) => { const w = wdOf(iso); return w !== 0 && w !== 6; };
function easterSunday(y) {
  const a = y % 19, b = Math.floor(y / 100), c = y % 100, d = Math.floor(b / 4), e = b % 4;
  const f = Math.floor((b + 8) / 25), g = Math.floor((b - f + 1) / 3), h = (19 * a + b - d - g + 15) % 30;
  const i = Math.floor(c / 4), k = c % 4, l = (32 + 2 * e + 2 * i - h - k) % 7, m = Math.floor((a + 11 * h + 22 * l) / 451);
  const month = Math.floor((h + l - 7 * m + 114) / 31), day = ((h + l - 7 * m + 114) % 31) + 1;
  return isoOf(y, month, day);
}
/** The n-th (1-based; -1 = last) weekday `wd` of a month. */
function nthWeekday(y, m, wd, n) {
  if (n > 0) {
    const first = isoOf(y, m, 1);
    return shiftIso(first, ((wd - wdOf(first) + 7) % 7) + 7 * (n - 1));
  }
  const last = new Date(Date.UTC(y, m, 0)).toISOString().slice(0, 10);
  return shiftIso(last, -((wdOf(last) - wd + 7) % 7));
}

/** NYSE closures for `year` by Rule 7.2: a Saturday holiday closes the
 *  preceding Friday, a Sunday holiday the following Monday, except that New
 *  Year's Day on a Saturday closes nothing (the preceding Friday ends a
 *  yearly accounting period). */
export function nyseClosures(year) {
  const out = {};
  const fixed = (m, d, name, { saturdayRule = true } = {}) => {
    const iso = isoOf(year, m, d), w = wdOf(iso);
    if (w === 6) { if (saturdayRule) out[shiftIso(iso, -1)] = `${name} (observed)`; }
    else if (w === 0) out[shiftIso(iso, 1)] = `${name} (observed)`;
    else out[iso] = name;
  };
  fixed(1, 1, "New Year's Day", { saturdayRule: false });
  out[nthWeekday(year, 1, 1, 3)] = "Martin Luther King, Jr. Day";
  out[nthWeekday(year, 2, 1, 3)] = "Washington's Birthday";
  out[shiftIso(easterSunday(year), -2)] = "Good Friday";
  out[nthWeekday(year, 5, 1, -1)] = "Memorial Day";
  fixed(6, 19, "Juneteenth National Independence Day");
  fixed(7, 4, "Independence Day");
  out[nthWeekday(year, 9, 1, 1)] = "Labor Day";
  out[nthWeekday(year, 11, 4, 4)] = "Thanksgiving Day";
  fixed(12, 25, "Christmas Day");
  // A Saturday 1 January of the next year leaves this year's 31 December open.
  return out;
}
/** NYSE 1:00 p.m. early closes for `year` (exchange_calendars XNYS). */
export function nyseEarlyCloses(year) {
  const out = {};
  const monToThu = (iso) => { const w = wdOf(iso); return w >= 1 && w <= 4; };
  if (monToThu(isoOf(year, 7, 3))) out[isoOf(year, 7, 3)] = "13:00";
  out[shiftIso(nthWeekday(year, 11, 4, 4), 1)] = "13:00";
  if (monToThu(isoOf(year, 12, 24))) out[isoOf(year, 12, 24)] = "13:00";
  return out;
}
/** Xetra closures for `year` by the fixed rule, weekdays only. */
export function xetraClosures(year) {
  const out = {};
  const e = easterSunday(year);
  for (const [iso, name] of [
    [isoOf(year, 1, 1), "New Year's Day"], [shiftIso(e, -2), "Good Friday"], [shiftIso(e, 1), "Easter Monday"], [isoOf(year, 5, 1), "Labor Day"],
    [isoOf(year, 12, 24), "Christmas Eve"], [isoOf(year, 12, 25), "Christmas Day"], [isoOf(year, 12, 26), "Boxing Day"], [isoOf(year, 12, 31), "New Year's Eve"],
  ]) if (isWeekday(iso)) out[iso] = name;
  return out;
}
/** LSE 12:30 half days for `year` (exchange_calendars XLON): 24 and 31
 *  December, or the preceding Friday when that day is on a weekend. */
export function lseHalfDays(year) {
  const out = {};
  for (const d of [24, 31]) {
    let iso = isoOf(year, 12, d);
    const w = wdOf(iso);
    if (w === 6) iso = shiftIso(iso, -1); else if (w === 0) iso = shiftIso(iso, -2);
    out[iso] = "12:30";
  }
  return out;
}
/** JPX year-end closures (exchange_calendars XTKS): 31 December, 2 and 3
 *  January, on weekdays (1 January is a national holiday). */
export function jpxYearEnd(year) {
  const out = {};
  for (const [iso] of [[isoOf(year, 1, 2)], [isoOf(year, 1, 3)], [isoOf(year, 12, 31)]]) if (isWeekday(iso)) out[iso] = "Market holiday (year-end)";
  return out;
}
/** HKEX 12:00 half days (exchange_calendars XHKG): the weekday eves of
 *  Christmas, New Year and Lunar New Year. */
export function hkexHalfDays(year, lunarNewYears = HK_LUNAR_NEW_YEAR) {
  const out = {};
  for (const iso of [isoOf(year, 12, 24), isoOf(year, 12, 31)]) if (isWeekday(iso)) out[iso] = "12:00";
  for (const lny of lunarNewYears) {
    const eve = shiftIso(lny, -1);
    if (eve.startsWith(String(year)) && isWeekday(eve)) out[eve] = "12:00";
  }
  return out;
}

