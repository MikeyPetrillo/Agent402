// The nightly backup covers the state database (src/backup.js stateTables /
// stageStateTable) and scripts/state-restore.js brings a table back: rows in,
// NDJSON out, rows back into a fresh schema, equal. Requires STATE_DATABASE_URL
// (CI fails without it).
import { mkdtempSync, rmSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { gunzipSync } from "node:zlib";
import { requireTestPg } from "./lib/test-pg.js";
requireTestPg({ label: "test-backup-state" });
const sdb = await import("../src/state-db.js");
const { stateTables, stageStateTable } = await import("../src/backup.js");

let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log(`ok - ${m}`); } else { fail++; console.error(`FAIL - ${m}`); } };
const DIR = mkdtempSync(join(tmpdir(), "backup-state-"));
try {
  await sdb.documents.put("a.json", { x: 1, nested: { y: [1, 2] } });
  await sdb.documents.put("b.json", "plain string body");
  await sdb.records.put("c", "r1", { n: 1 }); await sdb.records.put("c", "r2", { n: 2 });
  await sdb.logLines.append("s", { k: 1 }); await sdb.logLines.append("s", { k: 2 });
  await sdb.leases.acquire("L", { owner: "x", ttlMs: 60_000 });
  await sdb.imports.mark("a.json", { source: "/data/a.json", bytes: 10 });
  const tables = await stateTables();
  ok(["documents", "imports", "leases", "log_lines", "records"].every((t) => tables.includes(t)), `stateTables lists the schema's tables (${tables.join(",")})`);

  const gz = join(DIR, "documents.ndjson.gz");
  const n = await stageStateTable("documents", gz, { pageRows: 1 });
  const text = gunzipSync(readFileSync(gz)).toString("utf8");
  const rows = text.split("\n").filter(Boolean).map((l) => JSON.parse(l));
  ok(n === 2 && rows.length === 2, "stageStateTable writes one JSON object per row, paging through the table");
  ok(rows.some((r) => r.name === "a.json" && r.body.nested.y[1] === 2 && r.version === 1) && rows.some((r) => r.name === "b.json" && r.body === "plain string body"), "rows carry every column, bodies intact");
  let threw = false; try { await stageStateTable("bad;name", join(DIR, "x.gz")); } catch { threw = true; }
  ok(threw, "a table name outside the allowed shape is refused");

  const recGz = join(DIR, "records.ndjson.gz"); const recN = await stageStateTable("records", recGz);
  const logGz = join(DIR, "log_lines.ndjson.gz"); const logN = await stageStateTable("log_lines", logGz);
  ok(recN === 2 && logN === 2, "records and log lines stage too");

  // Restore after a wipe: same rows come back; a second restore adds nothing.
  const { restoreStateTable } = await import("./state-restore.js");
  const docText = text, recText = gunzipSync(readFileSync(recGz)).toString("utf8"), logText = gunzipSync(readFileSync(logGz)).toString("utf8");
  for (const tb of ["documents", "records", "log_lines"]) await sdb.stateQuery(`TRUNCATE ${sdb.stateDbSchema()}.${tb}`);
  ok((await sdb.documents.list()).length === 0, "the tables are empty before the restore");
  const r1 = await restoreStateTable("documents", docText);
  ok(r1.restored === 2 && r1.skipped === 0, "restore inserts every document row");
  const a = await sdb.documents.get("a.json");
  ok(a && a.body.nested.y[1] === 2 && a.version === 1, "a restored document reads back whole, version kept");
  const r2 = await restoreStateTable("documents", docText);
  ok(r2.restored === 0 && r2.skipped === 2, "a second restore adds nothing (ON CONFLICT DO NOTHING)");
  const r3 = await restoreStateTable("records", recText); const r4 = await restoreStateTable("log_lines", logText);
  ok(r3.restored === 2 && r4.restored === 2 && (await sdb.records.get("c", "r2")).n === 2 && (await sdb.logLines.count("s")) === 2, "records and log lines restore");
  // After a restore the next insert must not collide with a restored id: an
  // explicit-id INSERT does not advance a serial sequence, so the restore
  // advances it.
  await sdb.stateQuery(`TRUNCATE ${sdb.stateDbSchema()}.log_lines RESTART IDENTITY`);
  await restoreStateTable("log_lines", logText);
  let appendErr = null; try { await sdb.logLines.append("s", { k: 3 }); } catch (e) { appendErr = e.message; }
  ok(!appendErr && (await sdb.logLines.count("s")) === 3, `the first append after a restore into an emptied table succeeds (${appendErr || "ok"})`);

  // Every serial or identity column is found from the catalog, not a list:
  // a serial that is not the key, an identity key, values above 2^53.
  const S = sdb.stateDbSchema();
  await sdb.stateQuery(`CREATE TABLE ${S}.t_seq (k TEXT PRIMARY KEY, seq BIGSERIAL, n INT)`);
  await sdb.stateQuery(`CREATE TABLE ${S}.t_ident (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, big BIGINT, amount NUMERIC, body JSONB)`);
  await sdb.stateQuery(`CREATE TABLE ${S}.t_always (id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v TEXT)`);
  await sdb.stateQuery(`INSERT INTO ${S}.t_seq (k, n) SELECT 'k' || g, g FROM generate_series(1, 40) g`);
  await sdb.stateQuery(`INSERT INTO ${S}.t_ident (big, amount, body) VALUES (9007199254740993, 123456789012345678901234567890.000001, '{"big": 9007199254740993, "s": "x"}'::jsonb), (1, 0.1, '"bare"'::jsonb)`);
  await sdb.stateQuery(`INSERT INTO ${S}.t_always (v) SELECT 'v' || g FROM generate_series(1, 7) g`);
  const texts = {};
  for (const t of ["t_seq", "t_ident", "t_always"]) { const g = join(DIR, `${t}.ndjson.gz`); await stageStateTable(t, g); texts[t] = gunzipSync(readFileSync(g)).toString("utf8"); }
  ok(texts.t_ident.includes("9007199254740993"), "the staged object carries a bigint above 2^53 exactly");
  for (const t of ["t_seq", "t_ident", "t_always"]) await sdb.stateQuery(`TRUNCATE ${S}.${t} RESTART IDENTITY`);
  // A sequence already ahead of the restored rows never moves back (an id
  // handed out once is never handed out again).
  await sdb.stateQuery(`SELECT setval(pg_get_serial_sequence('${S}.t_always', 'id'), 100)`);
  for (const t of ["t_seq", "t_ident", "t_always"]) await restoreStateTable(t, texts[t]);
  let seqErr = null;
  try {
    await sdb.stateQuery(`INSERT INTO ${S}.t_seq (k, n) VALUES ('new', 0)`);
    await sdb.stateQuery(`INSERT INTO ${S}.t_ident (big) VALUES (2)`);
    await sdb.stateQuery(`INSERT INTO ${S}.t_always (v) VALUES ('new')`);
  } catch (e) { seqErr = e.message; }
  ok(!seqErr, `a new row goes into every serial and identity table after the restore (${seqErr || "ok"})`);
  const newSeq = (await sdb.stateQuery(`SELECT seq FROM ${S}.t_seq WHERE k = 'new'`)).rows[0]?.seq;
  ok(Number(newSeq) === 41, `a serial column that is not the key moves past the restored maximum (got ${newSeq})`);
  const alwaysNew = (await sdb.stateQuery(`SELECT id FROM ${S}.t_always WHERE v = 'new'`)).rows[0]?.id;
  ok(Number(alwaysNew) === 101, `a sequence ahead of the restored maximum is kept (next id ${alwaysNew})`);
  const big = (await sdb.stateQuery(`SELECT big::text AS b, amount::text AS a, body->>'big' AS jb, body::text AS raw FROM ${S}.t_ident WHERE id = 1`)).rows[0];
  ok(big?.b === "9007199254740993" && big?.jb === "9007199254740993" && big?.a === "123456789012345678901234567890.000001", `bigint, numeric and a big number inside jsonb come back exactly (${JSON.stringify(big)})`);
  const bare = (await sdb.stateQuery(`SELECT body::text AS t FROM ${S}.t_ident WHERE id = 2`)).rows[0]?.t;
  ok(bare === '"bare"', `a bare JSON string body stays a string (${bare})`);

  // A whole day into an EMPTY schema, no boot: the schema object creates the
  // tables, then the rows go in.
  const { stageStateTables } = await import("../src/backup.js");
  const { restoreStateDir } = await import("./state-restore.js");
  const dayDir = join(DIR, "day");
  const staged = await stageStateTables(dayDir);
  const fresh = `${S}_r`;
  const back = await restoreStateDir(dayDir, { schema: fresh });
  ok(back.schemaTables === staged.tables.length && back.schemaTables >= 7, `the schema object creates every table in an empty schema (${back.schemaTables})`);
  let same = true;
  for (const t of staged.tables) {
    const diff = Number((await sdb.stateQuery(`SELECT count(*) AS n FROM ((SELECT row_to_json(x)::jsonb FROM ${S}.${t.table} x EXCEPT ALL SELECT row_to_json(y)::jsonb FROM ${fresh}.${t.table} y) UNION ALL (SELECT row_to_json(y)::jsonb FROM ${fresh}.${t.table} y EXCEPT ALL SELECT row_to_json(x)::jsonb FROM ${S}.${t.table} x)) z`)).rows[0].n);
    if (diff) { same = false; console.error(`  ${t.table}: ${diff} row(s) differ`); }
  }
  ok(same, "every restored table equals its source row for row");
  const ix = (await sdb.stateQuery("SELECT count(*) AS n FROM pg_indexes WHERE schemaname = $1 AND indexname = 'log_lines_stream_id'", [fresh])).rows[0].n;
  ok(Number(ix) === 1, "secondary indexes are recreated");
  let freshErr = null; try { await sdb.stateQuery(`INSERT INTO ${fresh}.log_lines (stream, body) VALUES ('s', '{}')`); await sdb.stateQuery(`INSERT INTO ${fresh}.t_always (v) VALUES ('x')`); } catch (e) { freshErr = e.message; }
  ok(!freshErr, `inserts into the restored schema take new ids (${freshErr || "ok"})`);
  await sdb.stateQuery(`DROP SCHEMA ${fresh} CASCADE`);
  // The file-restore script hands a state/ directory to the same restore.
  const { execFileSync } = await import("node:child_process");
  const viaCli = `${S}_c`;
  const cliOut = execFileSync(process.execPath, ["scripts/backup-restore.js", "--state-dir", dayDir], { env: { ...process.env, STATE_DB_SCHEMA: viaCli }, encoding: "utf8" });
  const cliDocs = Number((await sdb.stateQuery(`SELECT count(*) AS n FROM ${viaCli}.documents`)).rows[0].n);
  const srcDocs = Number((await sdb.stateQuery(`SELECT count(*) AS n FROM ${S}.documents`)).rows[0].n);
  ok(cliDocs === srcDocs && /restored \d+ state table/.test(cliOut), `backup-restore.js --state-dir restores the state objects (${cliDocs}/${srcDocs})`);
  await sdb.stateQuery(`DROP SCHEMA ${viaCli} CASCADE`);

  const r5 = await restoreStateTable("documents", docText, { replace: true });
  ok(r5.restored === 2 && (await sdb.documents.list()).length === 2, "--replace truncates then restores");
  let bad = false; try { await restoreStateTable("no_such_table", "{}"); } catch { bad = true; }
  ok(bad, "a missing table is an error, not a silent no-op");
} finally {
  try { await sdb.__dropStateSchema(); } catch { /* already dropped */ }
  await sdb.closeStateDb();
  rmSync(DIR, { recursive: true, force: true });
}
console.log(`${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
