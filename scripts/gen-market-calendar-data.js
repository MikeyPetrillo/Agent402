// Writes src/tools/market-calendar-data.js: the public holiday lists the
// market-calendar tool (src/tools/exchange-calendars.js) reads, taken from
// three government publications whose licenses allow commercial reuse with
// a credit:
//   gov-uk.json     https://www.gov.uk/bank-holidays.json (England and Wales;
//                   Open Government Licence v3.0)
//   syukujitsu.csv  https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv
//                   (Cabinet Office, "National holidays"; Public Data License 1.0)
//   hk-en.json      https://www.1823.gov.hk/common/ical/en.json (general
//                   holidays, listed on DATA.GOV.HK; its terms allow commercial use)
// Run by hand when a year is published, with the three files downloaded into
// one directory:
//   node scripts/gen-market-calendar-data.js <dir>
// The output keeps only weekday dates from FROM to the last date each source
// lists, so the module is small and every row is the publisher's own.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) { console.error("usage: node scripts/gen-market-calendar-data.js <dir with gov-uk.json, syukujitsu.csv, hk-en.json>"); process.exit(2); }
const FROM = "2026-01-01";
const weekday = (iso) => { const d = new Date(`${iso}T00:00:00Z`).getUTCDay(); return d !== 0 && d !== 6; };

// English names for the Cabinet Office list's holiday names (our translation).
const JP_NAMES = {
  元日: "New Year's Day", 成人の日: "Coming of Age Day", 建国記念の日: "National Foundation Day", 天皇誕生日: "Emperor's Birthday",
  春分の日: "Vernal Equinox Day", 昭和の日: "Showa Day", 憲法記念日: "Constitution Memorial Day", みどりの日: "Greenery Day",
  こどもの日: "Children's Day", 海の日: "Marine Day", 山の日: "Mountain Day", 敬老の日: "Respect for the Aged Day",
  秋分の日: "Autumnal Equinox Day", スポーツの日: "Sports Day", 文化の日: "Culture Day", 勤労感謝の日: "Labor Thanksgiving Day",
  休日: "Holiday (Act on National Holidays, Article 3)",
};

const gb = JSON.parse(readFileSync(join(dir, "gov-uk.json"), "utf8").replace(/^﻿/, ""))["england-and-wales"].events
  .filter((e) => e.date >= FROM && weekday(e.date)).map((e) => [e.date, e.title.replace(/’/g, "'")]);

const csv = new TextDecoder("shift_jis").decode(readFileSync(join(dir, "syukujitsu.csv")));
const jp = [];
for (const line of csv.split(/\r?\n/).slice(1)) {
  const [d, name] = line.split(",");
  if (!d || !name) continue;
  const [y, m, dd] = d.split("/").map(Number);
  const iso = `${y}-${String(m).padStart(2, "0")}-${String(dd).padStart(2, "0")}`;
  if (iso < FROM || !weekday(iso)) continue;
  const en = JP_NAMES[name.trim()];
  if (!en) throw new Error(`no English name for ${name}`);
  jp.push([iso, en]);
}

const hkRaw = JSON.parse(readFileSync(join(dir, "hk-en.json"), "utf8").replace(/^﻿/, ""));
const hk = hkRaw.vcalendar[0].vevent.map((e) => {
  const s = String(e.dtstart[0]);
  return [`${s.slice(0, 4)}-${s.slice(4, 6)}-${s.slice(6, 8)}`, String(e.summary).replace(/’/g, "'")];
}).filter(([iso]) => iso >= FROM && weekday(iso));
const hkLunar = hkRaw.vcalendar[0].vevent.filter((e) => /^Lunar New Year.s Day$/.test(String(e.summary).replace(/’/g, "'")))
  .map((e) => { const s = String(e.dtstart[0]); return `${s.slice(0, 4)}-${s.slice(4, 6)}-${s.slice(6, 8)}`; }).filter((iso) => iso >= FROM);

const row = (pairs) => pairs.map(([d, n]) => `  [${JSON.stringify(d)}, ${JSON.stringify(n)}],`).join("\n");
const out = `// Generated by scripts/gen-market-calendar-data.js from the publishers'
// own files; do not edit by hand. Weekday dates from ${FROM}.
//
// England and Wales bank holidays: GOV.UK (https://www.gov.uk/bank-holidays.json).
// Contains public sector information licensed under the Open Government Licence v3.0.
export const GB_EW_BANK_HOLIDAYS = Object.freeze([
${row(gb)}
]);

// Japan national holidays: Cabinet Office, "National holidays"
// (https://www8.cao.go.jp/chosei/shukujitsu/gaiyou.html), Public Data License 1.0.
// English names are our translation.
export const JP_NATIONAL_HOLIDAYS = Object.freeze([
${row(jp)}
]);

// Hong Kong general holidays: the Government's public holidays dataset on
// DATA.GOV.HK (https://www.1823.gov.hk/common/ical/en.json).
export const HK_GENERAL_HOLIDAYS = Object.freeze([
${row(hk)}
]);
/** Lunar New Year's Day in the same dataset (weekends included). */
export const HK_LUNAR_NEW_YEAR = Object.freeze(${JSON.stringify(hkLunar)});
`;
writeFileSync(new URL("../src/tools/market-calendar-data.js", import.meta.url), out);
console.log(`wrote src/tools/market-calendar-data.js: GB ${gb.length}, JP ${jp.length}, HK ${hk.length} rows`);
